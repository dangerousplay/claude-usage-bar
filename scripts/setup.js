#!/usr/bin/env node
'use strict';
// Points ~/.claude/settings.json statusLine at this plugin's statusline.js (backs up first).
// Usage: node setup.js [--remove] [--plan pro|max5|max20] [--compact]
const fs = require('fs');
const path = require('path');
const L = require('./lib');

const settingsPath = path.join(L.CLAUDE_DIR, 'settings.json');
const settings = L.readJson(settingsPath, {});
const has = f => process.argv.includes(f);
const planIdx = process.argv.indexOf('--plan');

if (fs.existsSync(settingsPath)) fs.copyFileSync(settingsPath, settingsPath + '.bak-claude-usage');

if (has('--remove')) {
  delete settings.statusLine;
  console.log('Removed statusLine from ' + settingsPath);
} else {
  // Plugin updates move the install dir (cache/<marketplace>/usage-bar/<version>), so the
  // status line runs a stable launcher that finds the current install at runtime.
  const launcher = path.join(L.DATA_DIR, 'statusline-launcher.js');
  fs.mkdirSync(L.DATA_DIR, { recursive: true });
  fs.writeFileSync(launcher, `'use strict';
// Generated by usage-bar setup.js — resolves the installed plugin version on every run.
const fs = require('fs'), path = require('path');
let root = ${JSON.stringify(__dirname)};
try {
  const reg = JSON.parse(fs.readFileSync(path.join(${JSON.stringify(L.CLAUDE_DIR)}, 'plugins', 'installed_plugins.json'), 'utf8'));
  const key = Object.keys(reg.plugins || {}).find(k => k.startsWith('usage-bar@'));
  const p = key && reg.plugins[key][0] && path.join(reg.plugins[key][0].installPath, 'scripts');
  if (p && fs.existsSync(path.join(p, 'statusline.js'))) root = p;
} catch {}
require(path.join(root, 'statusline.js'));
`);
  const script = launcher.replace(/\\/g, '/');
  if (settings.statusLine && !String(settings.statusLine.command || '').includes('statusline')) {
    console.log('Replacing existing statusLine: ' + JSON.stringify(settings.statusLine));
  }
  settings.statusLine = { type: 'command', command: `node "${script}"`, padding: 0 };
  console.log('statusLine -> ' + settings.statusLine.command);
}

const patch = {};
if (planIdx >= 0) {
  const plan = process.argv[planIdx + 1];
  if (!L.PLAN_BUDGETS[plan]) { console.error('Unknown plan: ' + plan); process.exit(1); }
  patch.plan = plan;
}
if (has('--compact')) patch.expanded = false;
if (has('--full')) patch.expanded = true;
if (Object.keys(patch).length) { L.saveConfig(patch); console.log('Config updated: ' + JSON.stringify(patch)); }

fs.writeFileSync(settingsPath, JSON.stringify(settings, null, 2) + '\n');
console.log('Saved ' + settingsPath + ' (backup: settings.json.bak-claude-usage)');
